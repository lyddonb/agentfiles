"""Always-on instructions and the model roles file.

A profile's `mode`, `instructions` and `roles` become:

  * one block of always-on text, placed where each tool reads global instructions:
      claude-code  ~/.claude/rules/agentfiles.md            (a whole file agentfiles owns)
      codex        ~/.codex/AGENTS.md (or AGENTS.override.md if that is the one in use)
      pi           ~/.pi/agent/AGENTS.md (or whichever context file already exists there)
      opencode     ~/.config/opencode/AGENTS.md, only when that does not hide ~/.claude/CLAUDE.md
      cursor       a snippet to paste into Cursor Settings > Rules (no file on disk)
    In shared files the text sits between BEGIN/END agentfiles markers and nothing outside
    them is touched. Project scope writes only personal files (.claude/rules/agentfiles.md and
    .cursor/rules/agentfiles.mdc) and adds them to .git/info/exclude.

  * ~/.agents/roles.yaml (project: .agents/roles.yaml), which skills such as beau-mode read to
    pick a model per subagent role in the tool they run in.
"""
from __future__ import annotations

import hashlib
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .util import data_dir, run, short

BEGIN = "<!-- BEGIN agentfiles (generated by `agentfiles sync`; edit your profiles, not this block) -->"
END = "<!-- END agentfiles -->"
BLOCK_RE = re.compile(r"\n?<!-- BEGIN agentfiles\b[^>]*-->[ \t]*\r?\n.*?<!-- END agentfiles -->[ \t]*(?:\r?\n)?", re.S)
OWNED_HEADER = "<!-- Generated by `agentfiles sync`. Edit your agentfiles profiles, not this file. -->"


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:16]


# --------------------------------------------------------------------------- content

def render_body(profiles: list[str], mode: str | None, instructions: list[str], roles_path: str | None) -> str:
    """The Markdown that every tool receives (without markers)."""
    if not mode and not instructions and not roles_path:
        return ""
    parts = ["## Agent setup", "", f"_From agentfiles profiles: {', '.join(profiles)}._", ""]
    if mode:
        parts += [f"For any non-trivial task (a bug, a feature, a refactor, a performance problem, an "
                  f"investigation, a prototype, a skill edit, or an unattended run), load the `{mode}` skill "
                  f"first and follow it. Skip it for casual questions and quick answers, or when I say so.", ""]
    if roles_path:
        parts += [f"Model roles for subagents (`code`, `judgment`, `explorer`, `reviewers`) are in "
                  f"{roles_path}. Use the entry for the tool you are running in; a missing entry means "
                  f"use the current model.", ""]
    for text in instructions:
        parts += [text, ""]
    return "\n".join(parts).rstrip() + "\n"


def render_roles(profiles: list[str], roles: dict) -> str:
    header = ("# Generated by `agentfiles sync` from profiles: " + ", ".join(profiles) + "\n"
              "# Model per subagent role, per tool. Skills read the entry for the tool they run in.\n"
              "# A missing tool or `inherit` means: use the current model. Edit profiles, not this file.\n")
    return header + yaml.safe_dump({"version": 1, "roles": roles}, sort_keys=True, default_flow_style=False)


# --------------------------------------------------------------------------- blocks in shared files

def marker_problem(text: str) -> str:
    """Why the agentfiles markers in a file can't be edited safely, or "" when they can."""
    begins = len(re.findall(r"<!-- BEGIN agentfiles\b", text))
    ends = text.count(END)
    if begins == ends == 0 or (begins == ends == 1 and BLOCK_RE.search(text)):
        return ""
    if begins == ends == 1:
        return ("has agentfiles markers that are out of order or not on lines of their own; fix them "
                "by hand (BEGIN line, then END line) so agentfiles never deletes your text")
    return (f"has {begins} BEGIN and {ends} END agentfiles markers; fix them by hand "
            f"(one BEGIN and one END, or none) so agentfiles never deletes your text")


def upsert_block(text: str, body: str) -> str:
    block = f"{BEGIN}\n{body}{END}\n"
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _m: "\n" + block if _m.group(0).startswith("\n") else block, text, count=1)
    if not text:
        return block
    return text.rstrip("\n") + "\n\n" + block


def remove_block(text: str) -> str:
    """Drop the block, tidying blank lines only where it was; the rest of the file is unchanged."""
    m = BLOCK_RE.search(text)
    if not m:
        return text
    before, after = text[:m.start()], text[m.end():]
    if not before.strip():
        return after.lstrip("\r\n") if after.strip() else ""
    if not after.strip():
        return before.rstrip("\r\n") + "\n"
    b, a = before.rstrip("\n"), after.lstrip("\n")
    gap = len(before) - len(b) + len(after) - len(a)
    return b + "\n" * min(max(gap, 1), 2) + a


def has_block(text: str) -> bool:
    return bool(BLOCK_RE.search(text))


# --------------------------------------------------------------------------- where things go

@dataclass
class Placement:
    tool: str
    path: Path | None          # None: snippet only (no file the tool reads on disk)
    kind: str                  # "owned" (whole file is ours) or "block" (markers in a shared file)
    snippet: Path | None = None
    note: str = ""
    wrap: str = "md"           # "md" or "mdc" (Cursor rule with alwaysApply frontmatter)
    body: str | None = None    # overrides the shared body (Cursor's project copy is always complete)


def _first_existing(base: Path, names: list[str]) -> Path | None:
    for n in names:
        p = base / n
        if p.is_file() and p.read_text(errors="replace").strip():
            return p
    return None


def global_placements(targets: list[str]) -> list[Placement]:
    home = Path.home()
    out: list[Placement] = []
    if "claude-code" in targets:
        base = Path(os.environ.get("CLAUDE_CONFIG_DIR") or home / ".claude")
        out.append(Placement("claude-code", base / "rules" / "agentfiles.md", "owned"))
    if "codex" in targets:
        base = Path(os.environ.get("CODEX_HOME") or home / ".codex")
        target = _first_existing(base, ["AGENTS.override.md"]) or base / "AGENTS.md"
        out.append(Placement("codex", target, "block"))
    if "pi" in targets:
        base = Path(os.environ.get("PI_CODING_AGENT_DIR") or home / ".pi" / "agent")
        target = _first_existing(base, ["AGENTS.override.md", "AGENTS.md", "AGENTS.MD", "CLAUDE.md", "CLAUDE.MD"])
        out.append(Placement("pi", target or base / "AGENTS.md", "block"))
    if "opencode" in targets:
        oc = home / ".config" / "opencode" / "AGENTS.md"
        claude_md = Path(os.environ.get("CLAUDE_CONFIG_DIR") or home / ".claude") / "CLAUDE.md"
        if oc.is_file() or not claude_md.is_file():
            out.append(Placement(
                "opencode", oc, "block",
                note="" if oc.is_file() else
                     f"Created {short(oc)} for OpenCode. If you later add {short(claude_md)}, OpenCode "
                     f"will keep reading only {short(oc)}; add CLAUDE.md to `instructions` in opencode.json."))
        else:
            snip = data_dir() / "instructions" / "opencode.md"
            out.append(Placement(
                "opencode", None, "block", snippet=snip,
                note=(f"OpenCode reads {short(claude_md)} only while {short(oc)} does not exist, so "
                      f"agentfiles did not create it. Add \"{snip}\" to the `instructions` list in "
                      f"~/.config/opencode/opencode.json to give OpenCode the agentfiles block.")))
    if "cursor" in targets:
        snip = data_dir() / "instructions" / "cursor-user-rule.md"
        out.append(Placement(
            "cursor", None, "block", snippet=snip,
            note=f"Cursor keeps User Rules in its settings, not on disk. Paste {short(snip)} into "
                 f"Cursor Settings > Rules > User Rules (only needed when it changes)."))
    return out


def project_placements(project: Path, targets: list[str]) -> list[Placement]:
    out: list[Placement] = []
    if "claude-code" in targets:
        out.append(Placement("claude-code", project / ".claude" / "rules" / "agentfiles.md", "owned"))
    if "cursor" in targets:
        out.append(Placement("cursor", project / ".cursor" / "rules" / "agentfiles.mdc", "owned", wrap="mdc"))
    skipped = [t for t in targets if t in ("codex", "pi", "opencode")]
    if skipped:
        out.append(Placement(
            ",".join(skipped), None, "block",
            note=(f"{', '.join(skipped)} read only shared project files (AGENTS.md), which agentfiles does "
                  f"not edit. They still get your global agentfiles block.")))
    return out


def wrap_owned(body: str, wrap: str) -> str:
    if wrap == "mdc":
        return ("---\ndescription: agentfiles always-on instructions (generated; edit your profiles)\n"
                "alwaysApply: true\n---\n" + body)
    return OWNED_HEADER + "\n\n" + body


# --------------------------------------------------------------------------- git exclude

def exclude_in_git(project: Path, rel_paths: list[str], dry: bool) -> None:
    """Add paths to the repo's .git/info/exclude (personal, never committed)."""
    if not rel_paths:
        return
    p = run(["git", "-C", str(project), "rev-parse", "--git-path", "info/exclude"], check=False)
    if p.returncode != 0:
        return
    path = Path(p.stdout.strip())
    if not path.is_absolute():
        path = project / path
    existing = path.read_text().splitlines() if path.exists() else []
    missing = [r for r in rel_paths if r not in existing]
    if not missing or dry:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as fh:
        if existing and existing[-1].strip():
            fh.write("\n")
        if "# agentfiles" not in existing:
            fh.write("# agentfiles\n")
        fh.write("".join(f"{r}\n" for r in missing))


