"""Emit an APM (Microsoft Agent Package Manager) apm.yml for a profile.

Useful for team repos: commit the apm.yml and teammates run `apm install` without
needing agentfiles. Pins every dependency to the commit in agentfiles.lock.
"""
from __future__ import annotations

import re

import yaml

from .config import Config
from .resolve import Plan
from .store import Store

GITHUB_RE = re.compile(r"^(?:https://github\.com/|git@github\.com:)([^/]+/[^/]+?)(?:\.git)?/?$")


def _dep(cfg: Config, store: Store, source: str, rel: str, commit: str):
    src = cfg.sources[source]
    if src.is_local:
        return None
    m = GITHUB_RE.match(src.git or "")
    rel = "" if rel in (".", "") else rel
    if m:
        return f"{m.group(1)}/{rel}#{commit}" if rel else f"{m.group(1)}#{commit}"
    dep = {"git": src.git, "ref": commit}
    if rel:
        dep["path"] = rel
    return dep


def emit_apm(name: str, plan: Plan, cfg: Config, store: Store) -> str:
    deps, skipped = [], []
    for s in plan.skills:
        tree = store.tree(s.item.source)
        rel = s.path.relative_to(tree).as_posix() if s.path != tree else "."
        dep = _dep(cfg, store, s.item.source, rel, plan.digests[s.item.key][0])
        (deps.append(dep) if dep else skipped.append(s.item.ref))
    for p in plan.plugins:
        tree = store.tree(p.item.source)
        commit = plan.digests[p.item.key][0]
        # Marketplace entries that only list some skills of a repo (e.g. anthropics/skills'
        # document-skills) become one dependency per skill, not the whole repository.
        if p.claude is not None and p.claude.skills is not None:
            rels = [s.relative_to(tree).as_posix() for s in p.claude.skills]
        else:
            rels = [p.root.relative_to(tree).as_posix() if p.root != tree else "."]
        for rel in rels:
            dep = _dep(cfg, store, p.item.source, rel, commit)
            (deps.append(dep) if dep else skipped.append(p.item.ref))

    seen, unique = set(), []
    for d in deps:
        k = yaml.safe_dump(d)
        if k not in seen:
            seen.add(k)
            unique.append(d)

    doc = {"name": name, "version": "1.0.0", "dependencies": {"apm": unique}}
    header = [
        f"# Generated by `agentfiles emit-apm` from profile(s): {', '.join(plan.resolved.profiles)}",
        "# Pinned to the commits in agentfiles.lock. Regenerate instead of editing by hand.",
        "# Teammates: install APM (https://microsoft.github.io/apm/) and run `apm install`.",
    ]
    if skipped:
        header.append(f"# Skipped local-path sources: {', '.join(skipped)}")
    body = yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
    if plan.resolved.mcp:
        body += "\n# MCP servers from the profile (add the equivalent APM `mcp:` entries if wanted):\n"
        body += "".join(f"#   {line}\n" for line in
                        yaml.safe_dump(plan.resolved.mcp, sort_keys=True).splitlines())
    return "\n".join(header) + "\n" + body
